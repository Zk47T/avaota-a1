#!/usr/bin/env bash
# For SOURCE-BUILT redroid (AOSP 13 + redroid manifests): generate
#   out/aosp/vendor/powervr-a733/   -> copy to <redroid-src>/vendor/powervr-a733/
# Blobs become proper Soong prebuilt modules (no BUILD_BROKEN flags needed).
# Then in the redroid tree:
#   1) add to device/redroid/redroid_arm64_only/device.mk:
#        $(call inherit-product, vendor/powervr-a733/powervr-a733.mk)
#   2) cd vendor/redroid && patch -p1 < .../config/vendor_redroid-gpu_config-pvr.patch
#   3) lunch redroid_arm64_only-userdebug && m
set -euo pipefail
FARM=$(cd "$(dirname "$0")/.." && pwd)
B=$FARM/src/android-gpu/img-rgx/bxm
V=$FARM/out/aosp/vendor/powervr-a733
rm -rf "$V"; mkdir -p "$V"/prebuilts/{lib64/egl,lib64/hw,bin/hw}

cp "$B"/arm64/lib64/egl/lib{EGL,GLESv1_CM,GLESv2}_POWERVR_ROGUE.so "$V/prebuilts/lib64/egl/"
LIBS="libIMGegl libsrv_um libglslcompiler libusc libufwriter libpvrANDROID_WSEGL libPVRScopeServices libgpudataproducer libPVROCL"
for l in $LIBS; do cp "$B/arm64/lib64/$l.so" "$V/prebuilts/lib64/"; done
cp "$B/arm64/lib64/hw/vulkan.POWERVR_ROGUE.so" "$V/prebuilts/lib64/hw/vulkan.powervr.so"
cp "$B/arm64/lib64/hw/gralloc.powervr.so" "$V/prebuilts/lib64/hw/"
cp "$B/arm64/lib64/hw/android.hardware.graphics.mapper@4.0-impl.so" "$V/prebuilts/lib64/hw/"
cp "$B/arm64/bin/hw/android.hardware.graphics.allocator@4.0-service" "$V/prebuilts/bin/hw/"
cp "$B/arm64/bin/pvrsrvctl" "$B/arm64/bin/pvrdebug" "$V/prebuilts/bin/"
cp "$B"/etc/vintf/manifest/*.xml "$B/etc/powervr.ini" "$V/"
sed '/^service vendor.gralloc-4-0 /a\    disabled' \
  "$B/etc/init/android.hardware.graphics.allocator@4.0-service.img.rc" > "$V/android.hardware.graphics.allocator@4.0-service.img.rc"
cat > "$V/redroid-pvr.rc" <<'RC'
# set by vendor/redroid gpu_config.sh (patched) when the host exposes the "pvr" DRM device
on property:vendor.redroid.pvr=1
    start vendor.gralloc-4-0
RC

# emit one Soong prebuilt module
#   mod TYPE NAME SRC [relative_install_path] [stem] [init_rc] [vintf_fragment]
mod() {
  local type=$1 name=$2 src=$3 rel=${4:-} stem=${5:-} rc=${6:-} vintf=${7:-}
  printf '%s {\n    name: "%s",\n    srcs: ["%s"],\n' "$type" "$name" "$src"
  printf '    vendor: true,\n    compile_multilib: "64",\n    check_elf_files: false,\n    strip: { none: true },\n'
  [ -n "$rel" ]   && printf '    relative_install_path: "%s",\n' "$rel"
  [ -n "$stem" ]  && printf '    stem: "%s",\n' "$stem"
  [ -n "$rc" ]    && printf '    init_rc: ["%s"],\n' "$rc"
  [ -n "$vintf" ] && printf '    vintf_fragments: ["%s"],\n' "$vintf"
  printf '}\n\n'
}
lib() { mod cc_prebuilt_library_shared "$1" "$2" "${3:-}" "${4:-}" "" "${5:-}"; }
bin() { mod cc_prebuilt_binary "$@"; }
{
  echo "// Generated by 3.a733-android-farm/scripts/31-make-aosp-vendor-tree.sh"
  echo "// Allwinner A733 PowerVR BXM-4-64 userspace, DDK 24.2@6643903 (Radxa a733-radxa-v1.0)"
  echo
  for g in EGL GLESv1_CM GLESv2; do lib "lib${g}_POWERVR_ROGUE" "prebuilts/lib64/egl/lib${g}_POWERVR_ROGUE.so" egl; done
  for l in $LIBS; do lib "$l" "prebuilts/lib64/$l.so"; done
  lib vulkan.powervr  prebuilts/lib64/hw/vulkan.powervr.so  hw
  lib gralloc.powervr prebuilts/lib64/hw/gralloc.powervr.so hw
  # AOSP has no 4.0 default mapper impl, but use a unique module name anyway
  lib android.hardware.graphics.mapper@4.0-impl.img prebuilts/lib64/hw/android.hardware.graphics.mapper@4.0-impl.so hw \
      android.hardware.graphics.mapper@4.0-impl android.hardware.graphics.mapper@4.0-passthrough.img.xml
  bin android.hardware.graphics.allocator@4.0-service.img prebuilts/bin/hw/android.hardware.graphics.allocator@4.0-service hw \
      android.hardware.graphics.allocator@4.0-service android.hardware.graphics.allocator@4.0-service.img.rc \
      android.hardware.graphics.allocator@4.0.img.xml
  bin pvrsrvctl prebuilts/bin/pvrsrvctl
  bin pvrdebug  prebuilts/bin/pvrdebug
} > "$V/Android.bp"

cat > "$V/powervr-a733.mk" <<'MK'
# Inherit from device/redroid/redroid_arm64_only/device.mk
PRODUCT_PACKAGES += \
    libEGL_POWERVR_ROGUE libGLESv1_CM_POWERVR_ROGUE libGLESv2_POWERVR_ROGUE \
    libIMGegl libsrv_um libglslcompiler libusc libufwriter libpvrANDROID_WSEGL \
    libPVRScopeServices libgpudataproducer libPVROCL \
    vulkan.powervr gralloc.powervr \
    android.hardware.graphics.mapper@4.0-impl.img \
    android.hardware.graphics.allocator@4.0-service.img \
    pvrsrvctl pvrdebug
PRODUCT_COPY_FILES += \
    vendor/powervr-a733/redroid-pvr.rc:$(TARGET_COPY_OUT_VENDOR)/etc/init/redroid-pvr.rc \
    vendor/powervr-a733/powervr.ini:$(TARGET_COPY_OUT_VENDOR)/etc/powervr.ini
MK
cp "$FARM/config/vendor_redroid-gpu_config-pvr.patch" "$V/"
echo "ready: $V ($(du -sh "$V" | cut -f1)); modules: $(grep -c '^cc_prebuilt' "$V/Android.bp")"
